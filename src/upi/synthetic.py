"""SYNTHETIC UPI-shaped traffic for tests and demos. It is not real data and says nothing about real fraud.

Normal behaviour: each payer has a few favourite payees, a typical amount, a preferred time of day and one device.
Injected fraud (labelled 1), three documented patterns:
  * mule fan-in: many different payers send to the same new payee within hours;
  * account takeover: a payer's account is used from a new device for a burst of large transfers to new payees;
  * device ring: one device is used by many payers to pay ring payees.
To keep the task from being trivial there are LEGITIMATE look-alikes (label 0): flash-sale fan-in to a popular new shop, phone upgrades
(a new device for a normal payer), occasional large genuine transfers; fraud amounts overlap normal ones; and 10% of fraud is
"unreported" (labelled 0), as in real label data. Because every pattern is written by us, results on this data say nothing about real
fraud; use it only to prove the toolkit works end to end.
"""

from typing import Dict, List

import numpy as np

SYNTHETIC_NOTICE = "SYNTHETIC data generated by src/upi/synthetic.py: not real UPI traffic."
BASE_TS = 1_700_000_000.0


def generate(n_payers: int = 1500, n_payees: int = 600, days: int = 60, tx_per_payer_per_day: float = 0.5,
             seed: int = 0) -> List[Dict]:
    rng = np.random.default_rng(seed)
    payers = [f"p{i:05d}" for i in range(n_payers)]
    payees = [f"q{i:05d}" for i in range(n_payees)]
    scale = np.exp(rng.normal(6.0, 0.6, n_payers))                     # typical amount per payer (rupees)
    center = rng.uniform(8, 22, n_payers)                              # preferred hour
    fav = [rng.choice(n_payees, size=rng.integers(3, 9), replace=False) for _ in range(n_payers)]
    dev = [f"d{i:05d}" for i in range(n_payers)]
    rows: List[Dict] = []

    def add(t, payer_i, payee, amount, device, fraud, channel="app"):
        rows.append({"timestamp": float(t), "amount": float(max(round(amount, 2), 1.0)), "payer_id": payers[payer_i] if isinstance(payer_i, (int, np.integer)) else payer_i,
                     "payee_id": payee, "device_id": device, "channel": channel, "payee_category": None, "is_fraud": int(fraud)})

    n_normal = int(n_payers * days * tx_per_payer_per_day)
    who = rng.integers(0, n_payers, n_normal)
    day = rng.integers(0, days, n_normal)
    for i, d in zip(who, day):
        hour = float(np.clip(rng.normal(center[i], 2.5), 0, 23.9))
        payee = payees[int(rng.choice(fav[i]))] if rng.random() < 0.9 else payees[int(rng.integers(0, n_payees))]
        channel = "qr" if rng.random() < 0.25 else ("collect" if rng.random() < 0.03 else "app")
        add(BASE_TS + d * 86400 + hour * 3600, int(i), payee, scale[i] * np.exp(rng.normal(0, 0.5)), dev[i], 0, channel)

    # legitimate look-alikes (label 0), spread over the whole period
    n_fraud_target = max(int(n_normal * 0.012), 30)
    n_lookalike = max(int(np.ceil(n_fraud_target / 11.0)), 12)
    for _ in range(n_lookalike):                                           # flash sale: many payers pay one new shop within hours
        shop, t0 = f"shop{int(rng.integers(0, 1_000_000)):06d}", BASE_TS + float(rng.uniform(4, days - 1)) * 86400 + float(rng.uniform(0, 12)) * 3600
        for i in rng.choice(n_payers, size=int(rng.integers(12, 26)), replace=False):
            add(t0 + rng.uniform(0, 3 * 3600), int(i), shop, scale[i] * rng.uniform(0.6, 2.0), dev[i], 0)
    for _ in range(max(n_payers // 40, 20)):                               # phone upgrade: a new device, a few normal payments
        i = int(rng.integers(0, n_payers))
        new_dev, t0 = f"new{int(rng.integers(0, 1_000_000)):06d}", BASE_TS + float(rng.uniform(4, days)) * 86400
        for _ in range(int(rng.integers(3, 6))):
            add(t0 + rng.uniform(0, 3600), i, payees[int(rng.choice(fav[i]))], scale[i] * rng.uniform(0.5, 1.5), new_dev, 0)
    for _ in range(max(n_payers // 30, 20)):                               # large genuine transfer to a new payee (rent, family, a purchase)
        i = int(rng.integers(0, n_payers))
        add(BASE_TS + float(rng.uniform(4, days)) * 86400 + float(rng.uniform(0, 20)) * 3600, i, payees[int(rng.integers(0, n_payees))],
            scale[i] * rng.uniform(3, 8), dev[i], 0)

    n_bursts = max(int(np.ceil(n_fraud_target / 11.0)), 12)          # an average burst has about 11 fraudulent payments
    burst_days = np.linspace(4.0, days - 1.5, n_bursts) + rng.uniform(-0.3, 0.3, n_bursts)   # one burst per slot, spread over the whole period
    for burst_day in burst_days:
        kind = rng.choice(["mule", "takeover", "ring"], p=[0.4, 0.4, 0.2])
        t0 = BASE_TS + float(burst_day) * 86400 + float(rng.uniform(0, 12)) * 3600
        if kind == "mule":
            mule = f"mule{int(rng.integers(0, 1_000_000)):06d}"
            victims = rng.choice(n_payers, size=int(rng.integers(12, 26)), replace=False)
            for i in victims:
                add(t0 + rng.uniform(0, 3 * 3600), int(i), mule, scale[i] * rng.uniform(1.0, 3.5), dev[i], 1)
        elif kind == "takeover":
            i = int(rng.integers(0, n_payers))
            attacker_device = f"atk{int(rng.integers(0, 1_000_000)):06d}"
            for _ in range(int(rng.integers(3, 7))):
                add(t0 + rng.uniform(0, 1200), i, payees[int(rng.integers(0, n_payees))], scale[i] * rng.uniform(1.0, 6.0), attacker_device, 1)
        else:
            ring_device = f"ring{int(rng.integers(0, 1_000_000)):06d}"
            ring_payees = [f"rp{int(rng.integers(0, 1_000_000)):06d}" for _ in range(3)]
            for i in rng.choice(n_payers, size=int(rng.integers(8, 13)), replace=False):
                add(t0 + rng.uniform(0, 6 * 3600), int(i), ring_payees[int(rng.integers(0, 3))], scale[i] * rng.uniform(0.8, 3.0), ring_device, 1)

    for r in rows:                                                          # 10% of fraud never gets reported: the label says legitimate
        if r["is_fraud"] == 1 and rng.random() < 0.10:
            r["is_fraud"] = 0
    rows.sort(key=lambda r: r["timestamp"])
    for k, r in enumerate(rows):
        r["transaction_id"] = f"t{k:08d}"
    return rows
